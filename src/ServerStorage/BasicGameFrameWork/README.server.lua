--[[
	Basic Game Framework by Thurzin54 (@oigaleratudobemm) | 13/09/2025
	
	How to setup the framework:
	
	Put every folder in the correct place by the name of the folder and UNGROUP (Ctrl + U).
	Example:
		|	ReplicatedStorage(Folder) --> ReplicatedStorage(Game Service)
	
	For every component, service and controller class, have a example script with the basic
	framework already done, you can copy and paste it to create a new script of the same class.
	(Example scripts will be named with "_" in the begin of the name, example: _TestScript)
	
	Note: by adding new packages, you must add the Packages folder to the ReplicatedStorage,
	with the package system added into _index folder and a module script in Packages folder to
	require the package.
	
	This framework already includes a simple SoundEffects system, you can use it as a reference
	to create your own systems and use it in your game.
