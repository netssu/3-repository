--[[ Monster info.

Name: Flayed
Height: 2,5m

Lore: The pain is eternal. The skin can be removed, but the torment never disappears.

Flayed wasn't born. He was created.

The records of the Morcant Asylum tell of patients who should never have existed. Among them was a man
known only as "Patient 27", a failed experiment by the asylum's doctors. His original identity was erased,
and his body was subjected to brutal medical procedures, pain resistance tests, and mutilations without
anesthesia. But the real horror happened when he didn't die.

For unknown reasons, Patient 27 survived each procedure, even when his skin was completely peeled off.
His body refused to die, but it also wouldn't heal properly. He has become an abomination of exposed flesh,
exposed nerves and an absolute hatred for everything that still lives.

In one of the asylum's old records, a doctor described the last attempt to contain a creature:

"He doesn't talk. He doesn't react like a human being. When we locked him in, he just stood there,
breathing with that wet, grotesque sound. But when we turned off the lights, he disappeared. He didn't
run away... he just stopped being there."

The corridors of Block-B still have suggestions from the past. If someone stays inside too long, you'll
hear heavy breathing behind you... but when you turn around, you won't see anything.

Until it's too late.

